import { invoke } from "@tauri-apps/api/core";
import type * as T from "./types";

const call = <R>(cmd: string, args?: Record<string, unknown>) => invoke<R>(cmd, args);

export const api = {
  startup: () => call<T.StartupInfo>("startup"),
  settings: () => call<T.Settings>("get_settings"),
  settingsPath: () => call<string>("settings_path"),
  /** `base`: the settings this change started from; only what differs from it is saved. */
  saveSettings: (settings: T.Settings, base?: T.Settings) => call<void>("save_settings", { settings, base: base ?? null }),
  shelfAdd: (system: string, release: string, region: string | null, fields: T.CopyFields) => call<T.ShelfCopy>("shelf_add", { system, release, region, fields }),
  shelfUpdate: (id: string, fields: T.CopyFields) => call<T.ShelfCopy>("shelf_update", { id, fields }),
  shelfRemove: (id: string) => call<void>("shelf_remove", { id }),
  shelfLocations: () => call<string[]>("shelf_locations"),
  shelfReleases: (system: string, query: string) => call<T.ReleaseHit[]>("shelf_releases", { system, query }),
  shelfCsvColumns: (text: string) => call<[string[], T.CsvMapping]>("shelf_csv_columns", { text }),
  shelfCsvPreview: (text: string, mapping: T.CsvMapping | null, console: string | null) => call<T.ImportRow[]>("shelf_csv_preview", { text, mapping, console }),
  readCsvFile: (path: string) => call<string>("read_csv_file", { path }),
  shelfCsvImport: (rows: T.ImportRow[]) => call<number>("shelf_csv_import", { rows }),
  completion: (system: string, options: T.CompletionOptions) => call<T.Completion>("completion", { system, options }),
  completionSummary: (options: T.CompletionOptions) => call<T.CompletionSummary[]>("completion_summary", { options }),
  syncStatus: () => call<T.SyncStatus>("sync_status"),
  syncConnect: (url: string, password: string) => call<T.RootMap[] | null>("sync_connect", { url, password }),
  syncRestore: (mapping: T.RootMap[]) => call<number>("sync_restore", { mapping }),
  /** starts a sync as a job (or returns the one already going) */
  syncNow: () => call<number>("sync_now"),
  syncDisconnect: () => call<void>("sync_disconnect"),
  systems: () => call<T.SystemSummary[]>("systems"),
  allSystems: () => call<[string, string][]>("all_systems"),
  games: (filter: T.GameFilter, sort: T.GameSort, offset: number, limit: number) => call<T.Page<T.GameRow>>("games", { filter, sort, offset, limit }),
  gameIdsFor: (filter: T.GameFilter) => call<number[]>("game_ids_for", { filter }),
  gameDetail: (id: number) => call<T.GameDetail>("game_detail", { id }),
  scan: (full: boolean) => call<number>("scan", { full }),
  lastScan: () => call<T.ScanReport | null>("last_scan"),
  jobs: () => call<T.JobInfo[]>("jobs_list"),
  cancelJob: (id: number) => call<void>("job_cancel", { id }),
  clearJobs: () => call<void>("jobs_clear"),
  planRenames: (gameIds: number[], useMatched: number[] = []) => call<T.RenameItem[]>("plan_renames", { gameIds, useMatched }),
  applyRenames: (items: T.RenameItem[]) => call<T.BatchResult>("apply_renames", { items }),
  undo: (batchId: string) => call<T.BatchResult>("undo", { batchId }),
  history: () => call<T.BatchInfo[]>("history"),
  hash: (scope: T.HashScope) => call<number>("hash", { scope }),
  setHashLevel: (level: T.HashLevel) => call<void>("set_hash_level", { level }),
  pauseHashing: (paused: boolean) => call<void>("pause_hashing", { paused }),
  hashState: () => call<T.HashState>("hash_state"),
  importDat: (system: string, path: string) => call<{ name: string; version: string; games: number; roms: number }>("import_dat", { system, path }),
  verify: (system: string) => call<{ verified: number; bad: number; unknown: number }>("verify", { system }),
  missing: (system: string) => call<string[]>("missing", { system }),
  dupes: (system: string | null) => call<T.DupeGroup[]>("dupes", { system }),
  junk: () => call<T.JunkItem[]>("junk"),
  sourcesStatus: () => call<T.SourceStatus[]>("sources_status"),
  checkConsoles: () => call<number>("check_consoles"),
  downloadDats: (systems: string[] = []) => call<number>("download_dats", { systems }),
  downloadSwitchTitledb: () => call<number>("download_switch_titledb"),
  setPlay: (gameId: number, play: T.PlayInfo) => call<T.PlayInfo>("set_play", { gameId, play }),
  playSummary: () => call<T.PlaySummary>("play_summary"),
  collections: () => call<T.CollectionSummary[]>("collections"),
  collection: (id: string) => call<T.CollectionDetail>("collection", { id }),
  createCollection: (name: string, gameIds: number[] = []) => call<string>("create_collection", { name, gameIds }),
  updateCollection: (id: string, name: string, notes: string | null, deleted = false) => call<void>("update_collection", { id, name, notes, deleted }),
  setCollectionItems: (id: string, entries: [string, string | null][]) => call<void>("set_collection_items", { id, entries }),
  collectionPreview: (text: string) => call<T.ImportPreview>("collection_preview", { text }),
  collectionImport: (text: string, choices: (number | null)[]) => call<string>("collection_import", { text, choices }),
  collectionExport: (id: string) => call<string>("collection_export", { id }),
  writeTextFile: (path: string, text: string) => call<void>("write_text_file", { path, text }),
  readTextFile: (path: string) => call<string>("read_text_file", { path }),
  addToCollection: (id: string, gameIds: number[]) => call<number>("add_to_collection", { id, gameIds }),
  reveal: (path: string) => call<void>("reveal", { path }),
  fetchGameArt: (gameId: number, force = false) => call<Record<string, string>>("fetch_game_art", { gameId, force }),
  compareContents: (fileIds: number[]) => call<number>("compare_contents", { fileIds }),
  layout: (system: string | null = null) => call<T.SystemLayout[]>("layout", { system }),
  fixLayout: (gameIds: number[]) => call<T.BatchResult>("fix_layout", { gameIds }),
  archivePaths: (paths: string[], reason: string) => call<[string, string][]>("archive_paths", { paths, reason }),
  archiveFiles: (fileIds: number[], reason: string) => call<[string, string][]>("archive_files", { fileIds, reason }),
  moveToTools: (paths: string[]) => call<T.BatchResult>("move_to_tools", { paths }),
  moveFile: (src: string, dstDir: string) => call<T.BatchResult>("move_file", { src, dstDir }),
  archiveList: () => call<T.ArchiveEntry[]>("archive_list"),
  archivePurge: (ids: number[]) => call<T.PurgeReport>("archive_purge", { ids }),
  archivePurgeExpired: (ids: number[]) => call<T.PurgeReport>("archive_purge_expired", { ids }),
  archivePurgeAll: () => call<T.PurgeReport>("archive_purge_all"),
  archiveRestore: (id: number) => call<string>("archive_restore", { id }),
  archiveExtend: (ids: number[], days: number) => call<void>("archive_extend", { ids, days }),
  actions: () => call<T.ActionInfo[]>("actions"),
  actionsForGames: (gameIds: number[]) => call<T.ApplicableAction[]>("actions_for_games", { gameIds }),
  requirements: (actionId: string) => call<T.Requirement[]>("requirements", { actionId }),
  runAction: (actionId: string, fileIds: number[]) => call<number>("run_action", { actionId, fileIds }),
  /** `explicit`: you asked for these games yourself, so any whose match you skipped come back */
  matchMetadata: (gameIds: number[], explicit = false) => call<number>("match_metadata", { gameIds, explicit }),
  /** look a game up afresh and send every option to Match review */
  chooseAgain: (gameId: number) => call<number>("choose_again", { gameId }),
  skip: (kind: T.SkipKind, key: string, label: string, systemId: string | null = null) => call<void>("skip", { kind, key, label, systemId }),
  unskip: (kind: T.SkipKind, key: string) => call<void>("unskip", { kind, key }),
  skipped: (kind: T.SkipKind) => call<T.Skipped[]>("skipped", { kind }),
  reviewList: () => call<T.ReviewItem[]>("review_list"),
  chooseMetadata: (gameId: number, candidate: T.MetaCandidate) => call<void>("choose_metadata", { gameId, candidate }),
  rejectMetadata: (gameId: number) => call<void>("reject_metadata", { gameId }),
  searchMetadata: (gameId: number, query: string) => call<T.MetaCandidate[]>("search_metadata", { gameId, query }),
  candidatePreview: (candidate: T.MetaCandidate) => call<string | null>("candidate_preview", { candidate }),
  importTitledb: (kind: string, path: string) => call<number>("import_titledb", { kind, path }),
  systemImages: () => call<Record<string, string>>("system_images"),
  fetchSystemImages: () => call<number | null>("fetch_system_images"),
  setSystemImage: (systemId: string, path: string | null) => call<void>("set_system_image", { systemId, path }),
  stats: () => call<T.Stats>("stats"),
  syncShared: () => call<number>("sync_shared"),
};
